TRIGRAM_IMAGE = {
    (1, 1, 1): "天", (1, 1, 0): "澤", (1, 0, 1): "火", (1, 0, 0): "雷",
    (0, 1, 1): "風", (0, 1, 0): "水", (0, 0, 1): "山", (0, 0, 0): "地",
}
IMAGE_ORDER = "天澤火雷風水山地"
GUA_NAME = {
    "天": ("乾", "履", "同人", "無妄", "姤", "訟", "遯", "否"),
    "澤": ("夬", "兌", "革", "隨", "大過", "困", "咸", "萃"),
    "火": ("大有", "睽", "離", "噬嗑", "鼎", "未濟", "旅", "晉"),
    "雷": ("大壯", "歸妹", "豐", "震", "恆", "解", "小過", "豫"),
    "風": ("小畜", "中孚", "家人", "益", "巽", "渙", "漸", "觀"),
    "水": ("需", "節", "既濟", "屯", "井", "坎", "蹇", "比"),
    "山": ("大畜", "損", "賁", "頤", "蠱", "蒙", "艮", "剝"),
    "地": ("泰", "臨", "明夷", "復", "升", "師", "謙", "坤"),
}
ORIGIN_YANG = {6: 0, 7: 1, 8: 0, 9: 1}
VAR_YANG = {6: 1, 7: 1, 8: 0, 9: 0}

def hexagram_name(yang_bits: list[int]) -> str:
    b1, b2, b3, b4, b5, b6 = yang_bits
    lower = TRIGRAM_IMAGE[(b1, b2, b3)]
    upper = TRIGRAM_IMAGE[(b4, b5, b6)]
    name = GUA_NAME[upper][IMAGE_ORDER.index(lower)]
    return f"{name}為{upper}" if upper == lower else f"{upper}{lower}{name}"
